#!/usr/bin/env bash
# CamStar TURN relay provisioning: renders turnserver.conf from .env and
# starts coturn via Docker Compose. Use --render-only to just write the
# config (bare-metal/systemd installs, see README.md).
set -euo pipefail
cd "$(dirname "$0")"

RENDER_ONLY=0
[[ "${1:-}" == "--render-only" ]] && RENDER_ONLY=1

if [[ ! -f .env ]]; then
  echo "error: .env not found. Copy .env.example to .env and fill it in:" >&2
  echo "  cp .env.example .env && openssl rand -hex 32" >&2
  exit 1
fi

# shellcheck disable=SC1091
set -a; . ./.env; set +a

: "${TURN_SECRET:?TURN_SECRET is empty in .env — generate one with: openssl rand -hex 32}"
TURN_REALM="${TURN_REALM:-camstar.live}"
TURN_LISTEN_PORT="${TURN_LISTEN_PORT:-3478}"
TURN_MIN_PORT="${TURN_MIN_PORT:-49160}"
TURN_MAX_PORT="${TURN_MAX_PORT:-49200}"

if [[ ${#TURN_SECRET} -lt 32 ]]; then
  echo "warning: TURN_SECRET looks short; use 32+ random bytes (openssl rand -hex 32)" >&2
fi

# external-ip: only when the NIC's address differs from the public one
# (cloud 1:1 NAT). Omit otherwise — coturn detects the local public IP.
EXTERNAL_LINE=""
if [[ -n "${TURN_EXTERNAL_IP:-}" ]]; then
  EXTERNAL_LINE="external-ip=$TURN_EXTERNAL_IP"
fi

# Deny relaying into private/special ranges so the relay cannot be used as
# a tunnel into the host's network. (Same block as coturn's example config.)
cat > turnserver.conf <<EOF
# Generated by ./deploy.sh — edit .env and re-run; do not edit here.
listening-port=$TURN_LISTEN_PORT
realm=$TURN_REALM
use-auth-secret
static-auth-secret=$TURN_SECRET
fingerprint
no-cli
no-multicast-peers
stale-nonce=600
user-quota=12
total-quota=100
min-port=$TURN_MIN_PORT
max-port=$TURN_MAX_PORT
log-file=stdout
$EXTERNAL_LINE
denied-peer-ip=0.0.0.0-0.255.255.255
denied-peer-ip=10.0.0.0-10.255.255.255
denied-peer-ip=127.0.0.0-127.255.255.255
denied-peer-ip=169.254.0.0-169.254.255.255
denied-peer-ip=172.16.0.0-172.31.255.255
denied-peer-ip=192.0.0.0-192.0.0.255
denied-peer-ip=192.0.2.0-192.0.2.255
denied-peer-ip=192.88.99.0-192.88.99.255
denied-peer-ip=192.168.0.0-192.168.255.255
denied-peer-ip=198.18.0.0-198.19.255.255
denied-peer-ip=198.51.100.0-198.51.100.255
denied-peer-ip=203.0.113.0-203.0.113.255
denied-peer-ip=240.0.0.0-255.255.255.255
EOF
chmod 600 turnserver.conf
echo "rendered turnserver.conf"

if [[ "$RENDER_ONLY" == "1" ]]; then
  echo "render-only mode: not starting Docker. Next steps in README.md (bare metal)."
  exit 0
fi

if ! docker compose version >/dev/null 2>&1; then
  echo "error: docker compose plugin not found. Install Docker, or see README.md" >&2
  echo "for the bare-metal coturn path (re-run with --render-only)." >&2
  exit 1
fi

docker compose up -d
docker compose logs --tail 15 coturn || true

cat <<EOF

coturn is up. Remaining steps:
  1. Firewall: open UDP+TCP $TURN_LISTEN_PORT and UDP $TURN_MIN_PORT-$TURN_MAX_PORT
  2. On the API service, set:
       CAMSTAR_TURN_URL=turn:<public-host-or-ip>:$TURN_LISTEN_PORT
       CAMSTAR_TURN_SECRET=<same TURN_SECRET>
     then restart the API.
  3. Verify from README.md ("Verify") — the ice-servers response should
     now carry a turn: entry with a username/credential pair.
EOF
